"""Inline the firmware headers into one sketch.ino for wokwi.com, where a new
project starts with a single file. Output: wokwi/sketch.ino"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
src = root / "firmware" / "watertank"


def inline(name, seen):
    text = (src / name).read_text()
    def repl(m):
        inc = m.group(1)
        if inc in seen:
            return ""
        seen.add(inc)
        body = inline(inc, seen).replace("#pragma once\n", "")
        return f"// ----- {inc} -----\n{body}// ----- end {inc} -----\n"
    return re.sub(r'#include "([^"]+)"\n', repl, text)


out = root / "wokwi" / "sketch.ino"
out.write_text("// Generated by tools/wokwi_sketch.py from firmware/watertank/. Edit the files there.\n" + inline("watertank.ino", set()))
print(f"{out} {len(out.read_text())} chars")
